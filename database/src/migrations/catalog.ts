export function getMigrationByIndex(idx: number): MigrationMetadata | undefined {
  return MIGRATIONS_CATALOG.find((m) => m.index === idx);
}

export function getMigrationByTag(tag: string): MigrationMetadata | undefined {
  const normalized = tag.toLowerCase().replace(/\.sql$/, "");
  return MIGRATIONS_CATALOG.find(
    (m) => m.tag.toLowerCase() === normalized || m.filename.toLowerCase() === `${normalized}.sql`
  );
}

export function getAllMigrations(): MigrationMetadata[] {
  return [...MIGRATIONS_CATALOG];
}

export function getMigrationsForTable(tableName: string): MigrationMetadata[] {
  const lower = tableName.toLowerCase();
  return MIGRATIONS_CATALOG.filter(
    (m) =>
      m.tablesCreated.some((t) => t.toLowerCase() === lower) ||
      m.tablesAltered.some((t) => t.toLowerCase() === lower)
  );
}

export function getMigrationsByDomain(domain: MigrationDomain): MigrationMetadata[] {
  return MIGRATIONS_CATALOG.filter((m) => m.domain === domain);
}
