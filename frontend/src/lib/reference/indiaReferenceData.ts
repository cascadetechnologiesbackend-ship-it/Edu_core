export interface PincodeResolutionResult {
  state: string;
  stateCode: string;
  district?: string | undefined;
}

/**
 * Resolves Indian State and District from a 6-digit PIN code offline in <1ms.
 */
export function pincodeToStateDistrict(pincode: string | null | undefined): PincodeResolutionResult | null {
  if (!pincode) return null;
  const clean = pincode.trim();
  if (!/^\d{6}$/.test(clean)) return null;

  const prefix3 = clean.slice(0, 3);
  const target3 = PINCODE_PREFIX_3[prefix3];
  if (target3) {
    const stateObj = STATE_BY_CODE.get(target3.stateCode);
    if (stateObj) {
      return {
        state: stateObj.nameEn,
        stateCode: stateObj.code,
        district: target3.district,
      };
    }
  }

  const prefix2 = clean.slice(0, 2);
  const stateCode2 = PINCODE_PREFIX_2[prefix2];
  if (stateCode2) {
    const stateObj = STATE_BY_CODE.get(stateCode2);
    if (stateObj) {
      return {
        state: stateObj.nameEn,
        stateCode: stateObj.code,
      };
    }
  }

  return null;
}

/**
 * Normalizes legacy or free-text professionalTaxState values to canonical 2-letter codes.
 * e.g. "DL", "KARNATAKA", "karnataka", "Delhi", "KA" -> "KA" / "DL".
 * Returns null if unmatched.
 */
export function normalizeProfessionalTaxState(input: string | null | undefined): string | null {
  if (!input) return null;
  const trimmed = input.trim();
  if (!trimmed) return null;

  const upper = trimmed.toUpperCase();

  // Direct match on 2-letter state code
  if (STATE_BY_CODE.has(upper)) {
    return upper;
  }

  // Exact / case-insensitive match on state English or Hindi name
  for (const state of INDIAN_STATES) {
    if (
      state.nameEn.toUpperCase() === upper ||
      state.nameHi === trimmed ||
      state.nameEn.replace(/\s+/g, "").toUpperCase() === upper.replace(/\s+/g, "")
    ) {
      return state.code;
    }
  }

  // Common legacy aliases
  const legacyAliases: Record<string, string> = {
    UTTARANCHAL: "UK",
    ORISSA: "OR",
    PONDICHERRY: "PY",
    BENGAL: "WB",
    "WEST BENGAL": "WB",
    "NATIONAL CAPITAL TERRITORY OF DELHI": "DL",
    NCT: "DL",
  };

  if (legacyAliases[upper]) {
    return legacyAliases[upper];
  }

  return null;
}

/**
 * Returns districts for a state code (e.g. "KA") or state name (e.g. "Karnataka").
 */
export function getDistrictsForState(stateCodeOrName: string | null | undefined): DistrictItem[] {
  if (!stateCodeOrName) return [];
  const trimmed = stateCodeOrName.trim();
  const upper = trimmed.toUpperCase();

  let code = upper;
  if (!DISTRICTS_BY_STATE[code]) {
    const stateObj = INDIAN_STATES.find(
      (s) => s.nameEn.toUpperCase() === upper || s.nameHi === trimmed
    );
    if (stateObj) {
      code = stateObj.code;
    }
  }

  return DISTRICTS_BY_STATE[code] || [];
}

/**
 * Resolves an IndianState object by 2-letter code or name.
 */
export function getStateByCode(code: string | null | undefined): IndianState | undefined {
  if (!code) return undefined;
  return STATE_BY_CODE.get(code.trim().toUpperCase());
}
